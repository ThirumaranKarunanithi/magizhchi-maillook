-- The person's own sections (lanes beside Needs me / For my info / Can wait), and rules that file mail into them.
-- A section's mail carries lane = 's' || id.

CREATE TABLE sections (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        VARCHAR(40) NOT NULL,
    icon        VARCHAR(16) NOT NULL,
    color       VARCHAR(16) NOT NULL,
    position    INT NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_sections_user ON sections (user_id);

CREATE TABLE mail_rules (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    from_match     VARCHAR(400),
    subject_match  VARCHAR(200),
    to_match       VARCHAR(400),
    words_match    VARCHAR(200),
    lane           VARCHAR(16),
    mark_read      BOOLEAN NOT NULL DEFAULT FALSE,
    archive        BOOLEAN NOT NULL DEFAULT FALSE,
    enabled        BOOLEAN NOT NULL DEFAULT TRUE,
    made_by        VARCHAR(8) NOT NULL DEFAULT 'user',
    matched        INT NOT NULL DEFAULT 0,
    last_matched   TIMESTAMP WITH TIME ZONE,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_mail_rules_user ON mail_rules (user_id);
