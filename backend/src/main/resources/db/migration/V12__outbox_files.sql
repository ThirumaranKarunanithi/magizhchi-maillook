-- Outbox: mail waiting to go. Every send waits here for the undo window (or until the time the person
-- chose), and the server sends it then, so closing the tab after pressing Send loses nothing.
CREATE TABLE outbox (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_id  BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    payload     TEXT NOT NULL,
    send_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    status      VARCHAR(16) NOT NULL DEFAULT 'queued',
    error       TEXT,
    attempts    INT NOT NULL DEFAULT 0,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_outbox_due ON outbox (status, send_at);
CREATE INDEX ix_outbox_user ON outbox (user_id, send_at);

-- Files attached to a draft or to mail in the outbox, kept so a draft comes back with its attachments.
CREATE TABLE mail_files (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    draft_id      BIGINT REFERENCES drafts(id) ON DELETE CASCADE,
    outbox_id     BIGINT REFERENCES outbox(id) ON DELETE CASCADE,
    name          VARCHAR(500) NOT NULL,
    content_type  VARCHAR(200),
    size          BIGINT NOT NULL,
    data          BYTEA NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_mail_files_draft ON mail_files (draft_id);
CREATE INDEX ix_mail_files_outbox ON mail_files (outbox_id);
