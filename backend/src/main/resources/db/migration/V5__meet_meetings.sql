-- Meetings held in a Magizhchi Meet room that was started from an email thread: who came, who
-- missed it, and the AI recap, so the thread shows the meeting and the recap mail is one tap away.
CREATE TABLE meet_meetings (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id   BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    thread_key   VARCHAR(998) NOT NULL,
    card_id      VARCHAR(64) NOT NULL,
    card_name    VARCHAR(300),
    started_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    minutes      INT NOT NULL,
    report       TEXT NOT NULL,
    tasks_added  INT NOT NULL DEFAULT 0,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_meet_meeting UNIQUE (account_id, card_id, started_at)
);
CREATE INDEX ix_meet_meetings_thread ON meet_meetings (account_id, thread_key);
CREATE INDEX ix_meet_links_card ON meet_links (card_id);
