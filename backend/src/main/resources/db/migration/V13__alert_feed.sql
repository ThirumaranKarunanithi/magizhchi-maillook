-- Every alert MailLook raises (new mail, back from snooze, no reply, morning briefing, a send that failed),
-- kept for a week. Phones and browsers get them by Web Push; the desktop app reads them from here, so it
-- rings for the same things, reminders included, even on a server without push keys.
CREATE TABLE alerts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind        VARCHAR(16) NOT NULL,
    title       VARCHAR(200) NOT NULL,
    body        VARCHAR(400),
    url         VARCHAR(300),
    tag         VARCHAR(120),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_alerts_user ON alerts (user_id, id);
CREATE INDEX ix_alerts_age ON alerts (created_at);

-- When the desktop app last asked for alerts: the morning briefing also goes to people who use only it.
ALTER TABLE users ADD COLUMN desktop_seen_at TIMESTAMP WITH TIME ZONE;
