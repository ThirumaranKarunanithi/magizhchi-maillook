-- Bills from your mail: bills Magizhchi Data read out of mail, and what MailLook knows about senders.

CREATE TABLE bills (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message_id          BIGINT REFERENCES messages(id) ON DELETE SET NULL,  -- the mail it was first read from
    kind                VARCHAR(16) NOT NULL,             -- bill, receipt, credit_note
    vendor              VARCHAR(200),
    vendor_key          VARCHAR(200),                     -- lower-case vendor, for spotting the same bill twice
    vendor_gstin        VARCHAR(15),
    invoice_no          VARCHAR(100),
    invoice_date        DATE,
    due_date            DATE,
    amount              NUMERIC(14, 2),
    currency            VARCHAR(3) NOT NULL DEFAULT 'INR',
    cgst                NUMERIC(14, 2),
    sgst                NUMERIC(14, 2),
    igst                NUMERIC(14, 2),
    customer_ref        VARCHAR(100),
    pay_link            VARCHAR(1000),
    payee_account       VARCHAR(40),
    payee_ifsc          VARCHAR(20),
    autopay             BOOLEAN NOT NULL DEFAULT FALSE,
    status              VARCHAR(12) NOT NULL DEFAULT 'due',  -- due, paid
    paid_at             TIMESTAMP WITH TIME ZONE,
    source              VARCHAR(8),                       -- text, pdf, scan
    confidence          TEXT,                             -- JSON: field -> 0..1, from Data
    checked             BOOLEAN NOT NULL DEFAULT FALSE,   -- the person looked at it or fixed it
    remind_before_sent  BOOLEAN NOT NULL DEFAULT FALSE,
    remind_day_sent     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_bills_user_due ON bills (user_id, status, due_date);
CREATE INDEX ix_bills_invoice ON bills (user_id, vendor_key, invoice_no);

-- Where each mail stands: NULL not looked at, skip (no bill words), queued (waiting for Data),
-- read (a bill: bill_id says which), not_bill, no_credits, no_account, failed.
ALTER TABLE messages ADD COLUMN bill_state VARCHAR(12);
ALTER TABLE messages ADD COLUMN bill_id BIGINT REFERENCES bills(id) ON DELETE SET NULL;
ALTER TABLE messages ADD COLUMN bill_tries INT NOT NULL DEFAULT 0;
CREATE INDEX ix_messages_bill_state ON messages (bill_state);

-- Senders the person marked: always a biller (TRUE) or never (FALSE).
CREATE TABLE billers (
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    from_email  VARCHAR(320) NOT NULL,
    is_biller   BOOLEAN NOT NULL,
    PRIMARY KEY (user_id, from_email)
);

ALTER TABLE users ADD COLUMN bills_on BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN bills_on_at TIMESTAMP WITH TIME ZONE;     -- mail that arrives after this is checked as it comes
ALTER TABLE users ADD COLUMN bills_free_month VARCHAR(7);   -- 2026-11: the month the count below is for
ALTER TABLE users ADD COLUMN bills_free_used INT NOT NULL DEFAULT 0;
