CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(320) NOT NULL UNIQUE,
    name        VARCHAR(200),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE accounts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    email               VARCHAR(320) NOT NULL,
    display_name        VARCHAR(200),
    color               VARCHAR(16),
    provider            VARCHAR(32),
    imap_host           VARCHAR(255) NOT NULL,
    imap_port           INT NOT NULL,
    smtp_host           VARCHAR(255) NOT NULL,
    smtp_port           INT NOT NULL,
    password_enc        TEXT NOT NULL,
    status              VARCHAR(16) NOT NULL DEFAULT 'new',
    last_sync_at        TIMESTAMP WITH TIME ZONE,
    last_error          VARCHAR(1000),
    inbox_uid_validity  BIGINT,
    inbox_last_uid      BIGINT,
    sent_uid_validity   BIGINT,
    sent_last_uid       BIGINT,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_account_user_email UNIQUE (user_id, email)
);

CREATE TABLE messages (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id             BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    folder                 VARCHAR(16) NOT NULL,
    uid                    BIGINT,
    message_id             VARCHAR(998),
    thread_key             VARCHAR(998) NOT NULL,
    from_name              VARCHAR(320),
    from_email             VARCHAR(320),
    to_list                TEXT,
    cc_list                TEXT,
    subject                VARCHAR(2000),
    snippet                VARCHAR(400),
    body_text              TEXT,
    body_html              TEXT,
    attachments            TEXT,
    received_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    seen                   BOOLEAN NOT NULL DEFAULT FALSE,
    flagged                BOOLEAN NOT NULL DEFAULT FALSE,
    lane                   VARCHAR(16),
    lane_source            VARCHAR(16),
    list_unsubscribe       VARCHAR(2000),
    list_unsubscribe_post  BOOLEAN NOT NULL DEFAULT FALSE,
    unsubscribed           BOOLEAN NOT NULL DEFAULT FALSE,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX ix_messages_list   ON messages (account_id, folder, received_at);
CREATE INDEX ix_messages_uid    ON messages (account_id, folder, uid);
CREATE INDEX ix_messages_thread ON messages (account_id, thread_key);
CREATE INDEX ix_messages_from   ON messages (from_email);

CREATE TABLE sender_rules (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    sender_email  VARCHAR(320) NOT NULL,
    lane          VARCHAR(16) NOT NULL,
    CONSTRAINT uq_sender_rule UNIQUE (user_id, sender_email)
);

CREATE TABLE ai_cache (
    message_id  BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    kind        VARCHAR(16) NOT NULL,
    payload     TEXT NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (message_id, kind)
);
