-- Magizhchi Forms in MailLook.

-- Forms and polls sent from Compose: each person got their own copy and link, so we can tell who filled it.
CREATE TABLE form_sends (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_id   BIGINT NOT NULL,
    form_id      VARCHAR(60) NOT NULL,
    kind         VARCHAR(10) NOT NULL,            -- form | poll
    title        VARCHAR(300) NOT NULL,
    url          VARCHAR(600),
    email_key    VARCHAR(80),
    subject      VARCHAR(500),
    recipients   TEXT NOT NULL,                   -- JSON array of addresses
    message_ids  TEXT,                            -- JSON array of the Sent copies' ids
    filled       INT NOT NULL DEFAULT 0,
    sent_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reminded_at  TIMESTAMP WITH TIME ZONE
);
CREATE INDEX form_sends_user ON form_sends (user_id, sent_at);

-- Which Forms items an alert already went out for (approvals one by one, the day's responses as one).
CREATE TABLE forms_alerted (
    user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    item     VARCHAR(80) NOT NULL,
    at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, item)
);

-- lane: new responses wait on the Forms page; daily: one alert in the evening; off: neither.
ALTER TABLE users ADD COLUMN forms_responses VARCHAR(10) NOT NULL DEFAULT 'lane';
-- Their consent for Magizhchi Forms to send a form's mail from this mailbox (null: not allowed).
ALTER TABLE users ADD COLUMN forms_send_account BIGINT;
-- Seen Forms answer for this person (any Forms account at all); null until the first check.
ALTER TABLE users ADD COLUMN forms_linked BOOLEAN;
ALTER TABLE users ADD COLUMN forms_checked_at TIMESTAMP WITH TIME ZONE;
