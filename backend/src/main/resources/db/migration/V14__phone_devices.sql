-- The MailLook phone app: each phone's Firebase Cloud Messaging token, so alerts reach it while the app is
-- closed. A token belongs to whoever signed in last on that phone.
CREATE TABLE push_devices (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token         VARCHAR(512) NOT NULL UNIQUE,
    platform      VARCHAR(16) NOT NULL DEFAULT 'android',
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_push_devices_user ON push_devices (user_id);
