-- Snooze: hidden until snoozed_until; when it comes back (or a sent mail got no reply) back_at is set
-- and the mail sits at the top of its lane until it is read.
ALTER TABLE messages ADD COLUMN snoozed_until TIMESTAMP WITH TIME ZONE;
ALTER TABLE messages ADD COLUMN back_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE messages ADD COLUMN back_reason VARCHAR(16);
CREATE INDEX ix_messages_snoozed ON messages (snoozed_until);

-- "Remind me if nobody replies by ..." on a mail you sent.
CREATE TABLE followups (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    message_id  BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    due_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (message_id)
);
CREATE INDEX ix_followups_due ON followups (due_at);

-- A private note on a conversation, seen only by you.
CREATE TABLE thread_notes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_id  BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    thread_key  VARCHAR(998) NOT NULL,
    body        TEXT NOT NULL,
    pa_note_id  VARCHAR(64),
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (account_id, thread_key)
);

-- Browser and phone alerts (Web Push).
CREATE TABLE push_subscriptions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    endpoint    VARCHAR(1000) NOT NULL UNIQUE,
    p256dh      VARCHAR(200) NOT NULL,
    auth        VARCHAR(100) NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
