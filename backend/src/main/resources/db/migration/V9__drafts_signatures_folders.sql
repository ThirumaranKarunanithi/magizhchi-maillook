-- Drafts: what you're writing, saved as you type, so closing the composer loses nothing.
CREATE TABLE drafts (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_id           BIGINT REFERENCES accounts(id) ON DELETE CASCADE,
    mode                 VARCHAR(16) NOT NULL DEFAULT 'new',
    reply_to_message_id  BIGINT,
    to_list              TEXT,
    cc_list              TEXT,
    bcc_list             TEXT,
    subject              VARCHAR(2000),
    body                 TEXT,
    invite_card_id       VARCHAR(64),
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_drafts_user ON drafts (user_id, updated_at);

-- A signature per mailbox, added to new mail and replies.
ALTER TABLE accounts ADD COLUMN signature TEXT;

-- More folders than Inbox and Sent: Trash, Spam and the person's own folders.
-- A custom folder is stored as "F:" + its server name, so the column grows.
ALTER TABLE messages ALTER COLUMN folder SET DATA TYPE VARCHAR(300);

CREATE TABLE folder_cursors (
    account_id    BIGINT NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    code          VARCHAR(300) NOT NULL,
    server_name   VARCHAR(300) NOT NULL,
    uid_validity  BIGINT,
    last_uid      BIGINT,
    synced_at     TIMESTAMP WITH TIME ZONE,
    PRIMARY KEY (account_id, code)
);
